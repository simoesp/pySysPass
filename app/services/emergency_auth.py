"""Emergency Authentication Mode service (ADR-0014).

Manages the emergency mode activation flag, timeout enforcement, and provides
utilities for the emergency authentication endpoint.
"""
import json
import time
from datetime import UTC, datetime, timedelta
from pathlib import Path
from typing import Optional

from app.core.config import BASE_DIR, settings
from app.core.runtime_json_config import locked_path, write_text_atomically


# Default paths for the emergency activation flag
DEFAULT_EMERGENCY_FLAG_DIR = Path("/var/run/syspass")
DEFAULT_EMERGENCY_FLAG_FILE = DEFAULT_EMERGENCY_FLAG_DIR / "emergency-auth-active"

# Allow override via environment for testing and container deployments
EMERGENCY_FLAG_DIR = Path(
    settings.SYSPASS_EMERGENCY_FLAG_DIR
    if hasattr(settings, "SYSPASS_EMERGENCY_FLAG_DIR") and settings.SYSPASS_EMERGENCY_FLAG_DIR
    else DEFAULT_EMERGENCY_FLAG_DIR
)
EMERGENCY_FLAG_FILE = EMERGENCY_FLAG_DIR / "emergency-auth-active"

# Default timeout: 2 hours per ADR-0014 §3 (body header says 24h but acceptance criteria say 2h)
DEFAULT_TIMEOUT_HOURS = 2
EMERGENCY_SESSION_SECONDS = 3600  # 1 hour token lifetime per ADR-0014 §4


class EmergencyAuthError(Exception):
    """Raised when emergency authentication cannot proceed."""
    pass


def _flag_path() -> Path:
    """Get the current emergency flag file path."""
    return EMERGENCY_FLAG_FILE


def _read_flag() -> Optional[dict]:
    """Read and parse the emergency activation flag file."""
    flag_file = _flag_path()
    if not flag_file.exists():
        return None
    try:
        content = flag_file.read_text(encoding="utf-8")
        return json.loads(content)
    except (json.JSONDecodeError, OSError):
        return None


def _write_flag(data: dict) -> None:
    """Write the emergency activation flag file atomically."""
    flag_file = _flag_path()
    flag_file.parent.mkdir(parents=True, exist_ok=True)
    with locked_path(flag_file):
        write_text_atomically(flag_file, json.dumps(data, sort_keys=True) + "\n")


def is_active() -> bool:
    """Check if emergency authentication mode is currently active.

    Returns True if the flag file exists and has not expired.
    """
    flag = _read_flag()
    if not flag:
        return False

    # Check expiry
    try:
        activated_at = datetime.fromisoformat(flag.get("activated_at", ""))
        # Ensure both are naive for comparison
        if activated_at.tzinfo is not None:
            activated_at = activated_at.replace(tzinfo=None)
        timeout_hours = flag.get("timeout_hours", DEFAULT_TIMEOUT_HOURS)
        expires_at = activated_at + timedelta(hours=timeout_hours)
        now = datetime.now(UTC).replace(tzinfo=None)
        if now > expires_at:
            # Auto-expired: remove stale flag file
            deactivate()
            return False
    except (ValueError, KeyError):
        return False

    return True


def get_remaining_seconds() -> Optional[int]:
    """Get remaining seconds in the emergency activation window, or None if inactive."""
    flag = _read_flag()
    if not flag:
        return None
    try:
        activated_at = datetime.fromisoformat(flag.get("activated_at", ""))
        timeout_hours = flag.get("timeout_hours", DEFAULT_TIMEOUT_HOURS)
        expires_at = activated_at + timedelta(hours=timeout_hours)
        now = datetime.now(UTC).replace(tzinfo=None)
        if now >= expires_at:
            return None
        return int((expires_at - now).total_seconds())
    except (ValueError, KeyError):
        return None


def activate(timeout_hours: int = DEFAULT_TIMEOUT_HOURS, token: Optional[str] = None) -> dict:
    """Activate emergency authentication mode.

    Args:
        timeout_hours: Duration in hours before automatic deactivation (default: 2).
        token: Optional recovery token generated by the CLI script.

    Returns:
        Dict with activation details including expiry timestamp.
    """
    if timeout_hours <= 0:
        raise EmergencyAuthError("timeout_hours must be positive")

    now = datetime.now(UTC).replace(tzinfo=None)
    expires_at = now + timedelta(hours=timeout_hours)

    data = {
        "activated_at": now.isoformat(),
        "timeout_hours": timeout_hours,
        "expires_at": expires_at.isoformat(),
    }
    if token:
        data["token"] = token

    _write_flag(data)
    return data


def deactivate() -> bool:
    """Deactivate emergency authentication mode.

    Removes the flag file. Returns True if a flag was removed, False if already inactive.
    """
    flag_file = _flag_path()
    if flag_file.exists():
        flag_file.unlink()
        return True
    return False


def get_activation_info() -> Optional[dict]:
    """Get current activation info without modifying state."""
    return _read_flag()


def verify_recovery_token(username: str, provided_token: str, db) -> bool:
    """Verify a recovery token for a recovery account.

    Args:
        username: Emergency credentials username.
        provided_token: Token provided by the user.
        db: Database session.

    Returns:
        True if token is valid and not expired, False otherwise.
    """
    from app.models.account import EmergencyCredentials

    # First check the activation flag file for the token
    flag = _read_flag()
    if flag and flag.get("token"):
        activation_token = flag.get("token")
        if hmac.compare_digest(activation_token, provided_token):
            # Token matches activation token, now verify the user is a recovery account
            cred = (
                db.query(EmergencyCredentials)
                .filter(
                    EmergencyCredentials.username == username,
                    EmergencyCredentials.is_recovery_account.is_(True),
                    EmergencyCredentials.enabled.is_(True),
                )
                .first()
            )
            return cred is not None

    # Fallback: check user's stored recovery token
    cred = (
        db.query(EmergencyCredentials)
        .filter(
            EmergencyCredentials.username == username,
            EmergencyCredentials.is_recovery_account.is_(True),
            EmergencyCredentials.enabled.is_(True),
        )
        .first()
    )

    if not cred:
        return False

    if not cred.recovery_token:
        return False

    stored_token = (
        cred.recovery_token.decode() if isinstance(cred.recovery_token, bytes) else cred.recovery_token
    )
    if not hmac.compare_digest(stored_token, provided_token):
        return False

    # Check expiry
    if cred.recovery_token_expires_at:
        now = datetime.now(UTC).replace(tzinfo=None)
        if now > cred.recovery_token_expires_at:
            return False

    return True


import hmac

def constant_time_compare(val1: str, val2: str) -> bool:
    """Constant-time string comparison."""
    return hmac.compare_digest(val1, val2)


def log_emergency_event(
    db,
    action: str,
    description: str,
    username: str,
    ip: str,
    user_id: Optional[int] = None,
    level: str = "CRITICAL",
    mfa_verified: bool = False,
    token_used: bool = False,
):
    """Log an emergency authentication event at CRITICAL severity."""
    from app.services.security_log_service import EventLogService

    EventLogService(db).log_event(
        action=action,
        description=description,
        user_id=user_id if user_id is not None else 0,
        login=username,
        ip=ip,
        level=level,
    )


def emergency_session_fingerprint(cred) -> str:
    """Compute session fingerprint for emergency credentials.

    Uses the password_hash field instead of password (which is on User model).
    """
    import hmac
    import hashlib
    from app.core.config import settings

    password_hash = cred.password_hash or b""
    if isinstance(password_hash, str):
        password_hash = password_hash.encode("utf-8")
    message = b"sfp-v1|emergency|" + str(cred.id).encode() + b"|" + password_hash
    return hmac.new(settings.SECRET_KEY.encode(), message, hashlib.sha256).hexdigest()